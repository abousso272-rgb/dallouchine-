export type TranslationKey = keyof typeof fr;
const DICTS: Record<Lang, Partial<Record<TranslationKey, string>>> = { fr, en };

export function translate(lang: Lang, key: TranslationKey, vars?: Record<string, string | number>): string {
  const raw = DICTS[lang][key] ?? fr[key] ?? key;
  return vars ? raw.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? '')) : raw;
}

export function detectLang(): Lang {
  try {
    const nav = (navigator.languages?.[0] || navigator.language || 'fr').toLowerCase();
    return nav.startsWith('en') ? 'en' : 'fr';
  } catch {
    return 'fr';
  }
}
